import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const dir=path.dirname(fileURLToPath(import.meta.url));
const htmlPath=path.resolve(dir,'../living-library/live/atlas-l2-threejs-preview.html');
test('standalone 3D atlas visual design is interactive and safely isolated',async()=>{
 const html=await readFile(htmlPath,'utf8');
 assert.match(html,/<script type="importmap">/);
 assert.match(html,/three@0\.160\.1\/build\/three\.module\.js/);
 assert.match(html,/three\/addons\/controls\/OrbitControls\.js/);
 assert.match(html,/new THREE\.WebGLRenderer/);
 assert.match(html,/new THREE\.ExtrudeGeometry/);
 assert.match(html,/new THREE\.MeshPhysicalMaterial/);
 assert.match(html,/THREE\.CanvasTexture/);
 assert.match(html,/id="ordinary"/);
 assert.match(html,/id="upgraded"/);
 assert.match(html,/id="flip"/);
 assert.match(html,/id="angle"/);
 assert.match(html,/id="glow"/);
 assert.match(html,/id="upload"/);
 assert.match(html,/id="reset"/);
 assert.match(html,/id="imageInput"/);
 assert.match(html,/worldBinding|尚未正式認證/);
 assert.match(html,/不更改念動世界本體/);
 assert.doesNotMatch(html,/\blocalStorage\b/);
 assert.doesNotMatch(html,/\bObjectCraft\b/);
 assert.doesNotMatch(html,/ATLAS-0001/);
 assert.doesNotMatch(html,/\bfetch\s*\(/);
 assert.doesNotMatch(html,/\bXMLHttpRequest\b/);
});
