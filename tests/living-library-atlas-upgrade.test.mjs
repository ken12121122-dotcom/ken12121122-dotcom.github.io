import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url);
const Craft=require('../living-library/live/object-craft.js');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const fake=()=>{let raw=null,writes=0;return {getItem:k=>k===Craft.KEY?raw:null,setItem:(k,v)=>{assert.equal(k,Craft.KEY);raw=v;writes++},get writes(){return writes},data:()=>JSON.parse(raw||'{"objects":[]}')}};
const random={randomUUID:()=>'12345-abcdef'};
const clock=()=> '2026-10-16T13:00:00.000Z';
const make=(storage)=>Craft.createBlankCard(storage,random,clock);
test('blank ordinary cards cannot request certification or permanent number',()=>{
 const store=fake(),card=make(store),before=store.writes;
 assert.throws(()=>Craft.requestCardUpgrade(store,card.id,clock),/GBA/);
 assert.equal(store.writes,before);
 Craft.placeCard(store,card.id,'local.atlas.compendium',9,clock);
 assert.throws(()=>Craft.requestCardUpgrade(store,card.id,clock),/名稱/);
 assert.equal(Craft.listCards(store)[0].cardNumber,'');
});
test('an edited card can request GBA validation without becoming L2 or getting a number',()=>{
 const store=fake(),card=make(store);
 Craft.editCard(store,card.id,{title:'世界樹',description:'獨立世界物件'},clock);
 Craft.placeCard(store,card.id,'local.atlas.compendium',9,clock);
 const prior=Craft.listCards(store)[0],count=store.writes;
 const requested=Craft.requestCardUpgrade(store,card.id,clock);
 assert.equal(store.writes,count+1);
 assert.equal(requested.id,card.id);
 assert.equal(requested.status,'draft');
 assert.equal(requested.cardNumber,'');
 assert.equal(requested.upgradeRequest.state,'requested');
 assert.equal(requested.upgradeRequest.worldBinding,'unverified');
 assert.equal(requested.upgradeRequest.gbaReader,'local_reader_slot_9');
 assert.equal(requested.upgradeRequest.aiReview,'pending');
 assert.equal(requested.upgradeRequest.ownerApproval,'pending');
 assert.equal(requested.upgradeRequest.l2Certified,false);
 assert.equal(requested.upgradeRequest.permanentNumber,null);
 assert.equal(requested.upgradeRequest.contentRevision,prior.revision);
 assert.equal(Craft.read(store).version,1);
 assert.equal(Craft.requestCardUpgrade(store,card.id,clock).revision,requested.revision);
 assert.equal(store.writes,count+1,'repeated request is idempotent');
});
test('moving or editing after a request makes it stale; previously approved data stays untouched',()=>{
 const store=fake(),card=make(store);
 Craft.editCard(store,card.id,{title:'世界樹',description:'說明'},clock);
 Craft.placeCard(store,card.id,'local.atlas.compendium',9,clock);
 Craft.requestCardUpgrade(store,card.id,clock);
 const moved=Craft.placeCard(store,card.id,'local.atlas.collection',0,clock);
 assert.equal(moved.upgradeRequest.state,'stale');
 assert.equal(moved.upgradeRequest.staleReason,'card_placement_revised');
 assert.throws(()=>Craft.requestCardUpgrade(store,card.id,clock),/GBA/);
 Craft.placeCard(store,card.id,'local.atlas.compendium',9,clock);
 const req=Craft.requestCardUpgrade(store,card.id,clock);
 assert.equal(req.upgradeRequest.state,'requested');
 assert.equal(Craft.editCard(store,card.id,{description:'新版本'},clock).upgradeRequest.state,'stale');
 assert.equal(Craft.listCards(store)[0].cardNumber,'');
});
test('upgrading does not edit any other card, does not reserve a number, and is forbidden outside reader',async()=>{
 const store=fake(),first=make(store);
 const second=Craft.createBlankCard(store,{randomUUID:()=>'other-uuid'},clock);
 Craft.editCard(store,first.id,{title:'第一張',description:'A'},clock);
 Craft.placeCard(store,first.id,'local.atlas.compendium',8,clock);
 assert.throws(()=>Craft.requestCardUpgrade(store,first.id,clock),/GBA/);
 Craft.placeCard(store,first.id,'local.atlas.compendium',9,clock);
 Craft.requestCardUpgrade(store,first.id,clock);
 const other=Craft.listCards(store).find(c=>c.id===second.id);
 assert.equal(other.status,'draft');
 assert.equal(other.cardNumber,'');
 assert.equal(other.upgradeRequest,undefined);
 const layout=await readFile(path.join(root,'living-library/live/card-creation.html'),'utf8');
 assert.match(layout,/id="requestUpgrade"/);
 assert.match(layout,/Craft\.requestCardUpgrade/);
 assert.match(layout,/永久編號仍空白/);
});
